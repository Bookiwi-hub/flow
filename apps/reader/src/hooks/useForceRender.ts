/**
 * @author 조현지
 * @description 컴포넌트를 강제로 다시 렌더링하는 훅
 * @date 2025-03-25
 */

import { useState, useCallback } from 'react'

/**
 * 컴포넌트를 강제로 다시 렌더링하기 위한 React 훅이다.
 *
 * 이 훅은 컴포넌트의 상태를 실제로 변경하지 않고도 새 렌더링 사이클을
 * 트리거할 수 있는 함수를 제공한다. useState를 활용하되 상태 값 자체는
 * 중요하지 않고, 상태 업데이트 함수만을 사용한다.
 *
 * useCallback을 사용하여 컴포넌트가 리렌더링되더라도 같은 함수 인스턴스를
 * 유지하므로, 불필요한 재렌더링이 발생하지 않는다.
 *
 * 활용 사례:
 * 1. React 상태 시스템 밖에서 발생한 변화를 UI에 반영할 때
 * 2. 복잡한 상태 관리 로직에서 임시 해결책으로
 * 3. 디버깅 용도로 특정 시점의 렌더링 결과 확인
 * 4. ref 값의 변경이 있을 때 화면을 갱신해야 하는 경우
 *
 * @returns 호출 시 컴포넌트를 강제로 리렌더링하는 콜백 함수
 *
 * @example
 * function MyComponent() {
 *   const forceRender = useForceRender();
 *
 *   // 특정 조건에서 강제 리렌더링
 *   useEffect(() => {
 *     someExternalAPI.onUpdate(() => {
 *       // 외부 API 업데이트 시 화면 갱신
 *       forceRender();
 *     });
 *   }, []);
 *
 *   return <div>...</div>;
 * }
 */
export function useForceRender() {
  // 상태 값은 사용하지 않고 상태 업데이트 함수만 필요하므로
  // 첫 번째 요소(상태 값)는 무시하고 두 번째 요소(업데이트 함수)만 사용한다.
  // 초기값으로는 빈 객체를 설정한다(값은 중요하지 않음).
  const [, render] = useState({})

  // useCallback을 사용하여 함수를 메모이제이션하여
  // 컴포넌트가 리렌더링되어도 항상 같은 함수 인스턴스를 반환한다.
  // 의존성 배열이 비어있으므로 이 함수는 컴포넌트 수명 동안 동일하게 유지된다.
  return useCallback(() => {
    // 새로운 빈 객체를 전달하여 상태를 업데이트하고,
    // 이는 React에게 새로운 렌더링 사이클을 트리거하도록 신호를 보낸다.
    // 빈 객체 {}는 이전 상태와 항상 다른 참조를 가지므로 항상 리렌더링이 발생한다.
    render({})
  }, [])
}

/**
  이런 방식은 React의 선언적 패러다임과 맞지 않고, 성능 문제를 일으킬 수 있어 일반적으로는 권장되지 않는다. 
  대부분의 경우 React의 상태 관리(useState, useReducer)나 메모이제이션(useMemo, useCallback) 같은 표준 패턴으로 해결하는 것이 더 좋다.
  이 훅은 주로 임시 해결책이나 특수한 경우에 사용되는 "탈출구" 같은 역할을 한다.

  현재 사용되는 곳: 
  #1 셋팅 컴포넌트
  여기서 render() 함수를 호출하는 주요 목적은 Dropbox 인증 해제(로그아웃) 후 UI를 즉시 업데이트하는 것이다. 
  구체적인 프로세스는 다음과 같다:

  1. 사용자가 "Unauthorize" 버튼을 클릭하면, Dropbox 리프레시 토큰이 저장된 쿠키를 destroyCookie() 함수로 삭제한다.
  2. 쿠키가 삭제되었지만, React는 아직 이 상태 변화를 감지하지 못했다. 왜냐하면 쿠키는 React의 상태 시스템 외부에 있기 때문이다.
  3. 따라서 render() 함수를 호출하여 컴포넌트를 강제로 다시 렌더링한다.
  4. 컴포넌트가 다시 렌더링되면, parseCookies()가 다시 호출되어 최신 쿠키 상태를 반영한 refreshToken 값을 가져온다.
  5. 이제 refreshToken이 없어졌으므로 UI는 "Authorize" 버튼을 보여준다.

  이러한 패턴은 React의 상태 관리 바깥에 있는 쿠키, 로컬 스토리지 또는 외부 API 호출 같은 작업을 수행할 때 유용하다. 
  이런 외부 상태가 변경된 후에 컴포넌트 트리를 다시 렌더링하여 UI가 최신 상태를 반영하도록 만든다.

  #2 useTextSelection 훅
  여기에서는 텍스트 선택 기능을 개선하기 위한 중요한 역할을 하고 있다.

  1. 브라우저의 getSelection() API가 때로는 사용자가 새로운 텍스트 영역을 선택해도 이전에 반환한 것과 동일한 Selection 객체의 참조를 반환할 수 있다.
  2. React는 상태 업데이트 함수(setSelection)에 전달된 값이 이전 값과 참조적으로 동일하면 렌더링을 건너뛴다. 이것은 React의 성능 최적화 메커니즘이다.
  3. 하지만 Selection 객체의 내부 속성(선택된 텍스트 범위, 위치 등)은 변경되었을 수 있으므로, UI는 이 변경 사항을 반영해야 한다.
  4. 이럴 때 render() 함수를 호출하여 강제로 컴포넌트를 다시 렌더링함으로써, 동일한 Selection 객체 참조를 사용하더라도 UI가 최신 선택 상태를 올바르게 보여줄 수 있게 한다.
 */
